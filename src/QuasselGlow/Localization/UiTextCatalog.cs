    private static void AddFallbackAliases(IDictionary<string, IReadOnlyDictionary<string, string>> packs)
    {
        foreach (var code in SupportedLanguageCodes)
        {
            if (!packs.ContainsKey(code))
            {
                packs[code] = packs["en_US"];
            }
        }
    }

    private static IReadOnlyDictionary<string, string> Pack(params (string Key, string Value)[] entries)
    {
        return entries.ToDictionary(entry => entry.Key, entry => entry.Value, StringComparer.Ordinal);
    }
