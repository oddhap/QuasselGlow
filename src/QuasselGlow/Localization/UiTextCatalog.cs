    public string CurrentLanguageCode => _currentLanguageCode;

    public string this[string key] => Get(key);

    public string Get(string key)
    {
        if (TryGetValue(_currentLanguageCode, key, out var value))
        {
            return value;
        }

        var baseLanguage = GetBaseLanguage(_currentLanguageCode);
        if (!string.Equals(baseLanguage, _currentLanguageCode, StringComparison.OrdinalIgnoreCase)
            && TryGetValue(baseLanguage, key, out value))
        {
            return value;
        }

        return TryGetValue(DefaultLanguageCode, key, out value) ? value : key;
    }

    public string Format(string key, params object?[] arguments)
    {
        return string.Format(CultureInfo.CurrentCulture, Get(key), arguments);
    }

    public string SetLanguage(string? languageCode)
    {
        var resolved = ResolveLanguageCode(languageCode);
        if (string.Equals(_currentLanguageCode, resolved, StringComparison.OrdinalIgnoreCase))
        {
            return _currentLanguageCode;
        }

        _currentLanguageCode = resolved;
        OnPropertyChanged(nameof(CurrentLanguageCode));
        OnPropertyChanged("Item");
        OnPropertyChanged("Item[]");
        LanguageChanged?.Invoke(this, EventArgs.Empty);
        return _currentLanguageCode;
    }

    public static string ResolveLanguageCode(string? languageCode)
    {
        var normalized = NormalizeLanguageCode(languageCode);
        if (string.IsNullOrWhiteSpace(normalized))
        {
            normalized = NormalizeLanguageCode(CultureInfo.CurrentUICulture.Name);
        }

        if (string.IsNullOrWhiteSpace(normalized))
        {
            return DefaultLanguageCode;
        }

        if (SupportedLanguageSet.Contains(normalized))
        {
            return normalized;
        }

        var baseLanguage = GetBaseLanguage(normalized);
        if (SupportedLanguageSet.Contains(baseLanguage))
        {
            return baseLanguage;
        }

        return baseLanguage switch
        {
            "en" => "en_US",
            "no" => "nb",
            "nn" => "nb",
            "zh" => "zh_CN",
            _ => DefaultLanguageCode
        };
    }

    public static string NormalizeLanguageCode(string? languageCode)
    {
        if (string.IsNullOrWhiteSpace(languageCode))
        {
            return string.Empty;
        }

        var raw = languageCode.Trim().Replace('-', '_');
        var parts = raw.Split('_', StringSplitOptions.RemoveEmptyEntries);
        if (parts.Length == 0)
        {
            return string.Empty;
        }

        var language = parts[0].ToLowerInvariant();
        if (language is "no" or "nn")
        {
            language = "nb";
        }

        if (parts.Length == 1)
        {
            return language;
        }

        return $"{language}_{parts[1].ToUpperInvariant()}";
    }

    private static bool TryGetValue(string languageCode, string key, out string value)
    {
        if (Packs.TryGetValue(languageCode, out var pack) && pack.TryGetValue(key, out value!))
        {
            return true;
        }

        value = string.Empty;
        return false;
    }

    private static string GetBaseLanguage(string languageCode)
    {
        var separatorIndex = languageCode.IndexOf('_');
        return separatorIndex < 0 ? languageCode : languageCode[..separatorIndex];
    }

