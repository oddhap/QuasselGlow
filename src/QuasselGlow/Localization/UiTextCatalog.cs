    private static void ExtendPack(
        IDictionary<string, IReadOnlyDictionary<string, string>> packs,
        string languageCode,
        IReadOnlyDictionary<string, string> additions)
    {
        if (!packs.TryGetValue(languageCode, out var existing))
        {
            return;
        }

        var merged = new Dictionary<string, string>(existing, StringComparer.Ordinal);
        foreach (var (key, value) in additions)
        {
            merged[key] = value;
        }

        packs[languageCode] = merged;
    }

    private static IReadOnlyDictionary<string, string> Pack(params (string Key, string Value)[] entries)
    {
        return entries.ToDictionary(entry => entry.Key, entry => entry.Value, StringComparer.Ordinal);
    }
